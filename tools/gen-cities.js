// Rebuild site/cities.js: one centroid per distinct home_city|home_state in data/sources.json.
// Keeps the entries already in site/cities.js, geocodes the missing ones through Nominatim (1 request per second, cached in data/geocache.json under "city:" keys).
import fs from "node:fs";
const sources = JSON.parse(fs.readFileSync("data/sources.json", "utf8"));
const existing = {};
try {
  const txt = fs.readFileSync("site/cities.js", "utf8");
  for (const m of txt.matchAll(/"([^"]+\|[A-Z]{2})":\s*\[\s*(-?[\d.]+),\s*(-?[\d.]+)\s*\]/g)) existing[m[1]] = [+m[2], +m[3]];
} catch {}
const cachePath = "data/geocache.json";
const cache = fs.existsSync(cachePath) ? JSON.parse(fs.readFileSync(cachePath, "utf8")) : {};
const keys = [...new Set(sources.map((s) => s.home_city + "|" + s.home_state))].sort();
const out = {}; let fetched = 0, failed = [];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
for (const k of keys) {
  if (existing[k]) { out[k] = existing[k]; continue; }
  const ck = "city:" + k.toLowerCase();
  if (cache[ck] && cache[ck].lat) { out[k] = [cache[ck].lat, cache[ck].lng]; continue; }
  const [city, st] = k.split("|");
  const url = "https://nominatim.openstreetmap.org/search?format=jsonv2&limit=1&countrycodes=us&q=" + encodeURIComponent(`${city}, ${st}, USA`);
  try {
    const r = await fetch(url, { headers: { "User-Agent": "matcha-map/0.1 (+https://github.com/StevenMacchia/matcha-map)" } });
    const j = await r.json();
    if (j[0]) { out[k] = [+(+j[0].lat).toFixed(4), +(+j[0].lon).toFixed(4)]; cache[ck] = { lat: out[k][0], lng: out[k][1], source: "nominatim", at: new Date().toISOString() }; fetched++; }
    else failed.push(k);
  } catch (e) { failed.push(k + " (" + e.message + ")"); }
  await sleep(1100);
}
fs.writeFileSync(cachePath, JSON.stringify(cache, null, 2) + "\n");
const lines = Object.keys(out).sort().map((k) => `  ${JSON.stringify(k)}: [${out[k][0]}, ${out[k][1]}],`);
fs.writeFileSync("site/cities.js", `// City centroids (degrees) for every home_city|home_state in data/sources.json.\n// Generated by tools/gen-cities.js (Nominatim, cached); hand edits are kept on the next run.\nwindow.CITIES = {\n${lines.join("\n")}\n};\n`);
console.log(`${keys.length} cities, ${Object.keys(existing).length} kept, ${fetched} geocoded, ${failed.length} failed${failed.length ? ": " + failed.join(", ") : ""}`);
